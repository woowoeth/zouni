def amap_app(kw, city, nav_pts=None, mode='car'):
    """高德 App 的调起地址（iOS、安卓）；坐标统一用高德坐标（dev=0）"""
    t = {'car': 0, 'bus': 1, 'walk': 2}.get(mode, 0); nm = urllib.parse.quote(kw)
    if nav_pts:
        (a, b) = nav_pts; ga, gb = wgs2gcj(*a), wgs2gcj(*b)
